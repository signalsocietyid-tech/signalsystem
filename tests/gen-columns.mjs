// Generates assets/js/columns.js — the column list of every public table, built
// from supabase/schema.sql + supabase/migrations exactly like the tests do.
// db.js uses it so sync only sends real columns. Re-run after any schema change:
//   cd tests && npm run columns
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const root = new URL('../', import.meta.url);
const db = new PGlite();
await db.exec(`
  create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
  create schema auth; create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
  create publication supabase_realtime;`);
await db.exec(readFileSync(new URL('supabase/schema.sql', root), 'utf8').replace(/create extension if not exists "pgcrypto";/, ''));
const dir = new URL('supabase/migrations/', root);
for (const f of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) await db.exec(readFileSync(new URL(f, dir), 'utf8'));

const rows = (await db.query(`select table_name, array_agg(column_name::text order by ordinal_position) cols
  from information_schema.columns where table_schema = 'public' group by table_name order by table_name`)).rows;
const map = Object.fromEntries(rows.map((r) => [r.table_name, r.cols]));
writeFileSync(new URL('assets/js/columns.js', root),
  `/* GENERATED by tests/gen-columns.mjs from supabase/schema.sql + migrations — do not edit.\n   Columns per table; db.js sends only these when syncing to Supabase. */\nwindow.SignalColumns = ${JSON.stringify(map, null, 0).replace(/\],"/g, '],\n  "')};\n`);
console.log(`assets/js/columns.js ← ${rows.length} tables`);
